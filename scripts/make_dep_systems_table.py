#!/usr/bin/env python3
"""Assemble the deployed-configuration view of the deployment measurement.

The Tree-to-Spike row is the configuration that would actually ship: the
validation-selected exit where the exit was admitted, and the full window where
it was rejected on that dataset (CICIoT2023, Edge-IIoTset, ISCX-IDS2012,
NSL-KDD, UNSW-NB15 at seed 42). Reporting the exit row on a dataset that rejects
the exit would report a configuration nobody deploys.

Every column here is a single-run seed-42 deployment measurement: footprint,
batch-1 CPU latency and executed operations. Quality columns belong to the
five-seed tables and are deliberately absent, so the two cannot be mixed.

    python scripts/make_dep_systems_table.py
Output: results/tables/tab_dep_systems.{csv,tex}
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
IOT = ["ciciot2023", "ciciomt2024", "edgeiiot", "toniot"]
NAME = {"t2s_deployed": "Tree-to-Spike (deployed)", "dnn_tree": "DNN-Tree",
        "vanilla_snn": "Vanilla SNN", "tasnn": "TASNN",
        "compact_gbdt": "GBDT (compact)", "full_gbdt": "GBDT (full)"}
ORDER = ["t2s_deployed", "dnn_tree", "vanilla_snn", "tasnn", "compact_gbdt", "full_gbdt"]


def deployed(d: pd.DataFrame) -> pd.DataFrame:
    """Fold t2s_full / t2s_exit into the one row that ships per dataset."""
    ex = d[d.system == "t2s_exit"].set_index("dataset")
    fu = d[d.system == "t2s_full"].set_index("dataset")
    rows = []
    for ds in ex.index:
        disabled = bool(ex.loc[ds, "exit_disabled"])
        r = (fu if disabled else ex).loc[ds].copy()
        r["system"] = "t2s_deployed"
        r["dataset"] = ds
        r["exit_admitted"] = not disabled
        rows.append(r)
    keep = d[d.system.isin(ORDER)].copy()
    keep["exit_admitted"] = pd.NA
    return pd.concat([keep, pd.DataFrame(rows)], ignore_index=True)


def main():
    src = REPO / "results/deployment/deployment_measurements.csv"
    d = pd.read_csv(src, comment="#")
    a = deployed(d)
    a = a[a.system.isin(ORDER)]
    out = REPO / "results/tables"
    out.mkdir(parents=True, exist_ok=True)
    a.to_csv(out / "tab_dep_systems.csv", index=False)

    piv = a.pivot_table(index="dataset", columns="system", values="total_bytes").div(1024)
    lat = a.pivot_table(index="dataset", columns="system", values="p50_ms")
    print("footprint, KB (seed 42)")
    print(piv[[c for c in ORDER if c in piv]].round(1).to_string())
    print("\nbatch-1 CPU latency, ms (seed 42)")
    print(lat[[c for c in ORDER if c in lat]].round(2).to_string())
    i = a[a.dataset.isin(IOT)]
    print("\nIoT mean")
    m = i.groupby("system").agg(KB=("total_bytes", lambda x: x.mean() / 1024),
                                p50_ms=("p50_ms", "mean"))
    m["fits_128KB"] = [int((i[i.system == s].total_bytes <= 131072).sum()) for s in m.index]
    print(m.reindex([c for c in ORDER if c in m.index]).round(2).to_string())

    lines = [r"% generated by scripts/make_dep_systems_table.py from "
             r"results/deployment/deployment_measurements.csv",
             r"% ALL COLUMNS: single-run seed 42. Tree-to-Spike is the deployed "
             r"configuration (selected exit where admitted, full window where rejected).",
             r"\begin{tabular}{l" + "rr" * 1 + r"r}", r"\toprule",
             r"System & Footprint (KB) & $p_{50}$ (ms) & Fits 128\,KB \\", r"\midrule"]
    for s in ORDER:
        if s not in m.index:
            continue
        lines.append(f"{NAME[s]} & {m.loc[s, 'KB']:.1f} & {m.loc[s, 'p50_ms']:.2f} & "
                     f"{int(m.loc[s, 'fits_128KB'])}/4 \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "tab_dep_systems.tex").write_text("\n".join(lines) + "\n")
    print(f"\n[wrote] {out/'tab_dep_systems.csv'} and .tex")


if __name__ == "__main__":
    main()
