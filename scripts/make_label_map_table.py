#!/usr/bin/env python3
"""Appendix table: the exact native-label -> KDD 5-class mapping for
CIC-IDS2017 and CSE-CIC-IDS2018, generated from the loaders' LABEL_TO_CLASS
dicts (single source of truth: src/data/cicids2017.py, src/data/cseids2018.py)
plus post-mapping class counts computed from the processed data actually used
(CSE-CIC-IDS2018 at its configured 0.5 subsample, seed 42; CIC-IDS2017 full).

-> results/Journal_results/tables/table_label_mapping.tex
Run:  python scripts/make_label_map_table.py
"""
from __future__ import annotations
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src.data.cicids2017 import LABEL_TO_CLASS as MAP17
from src.data.cseids2018 import LABEL_TO_CLASS as MAP18
from src.data import get_dataset

TAB = REPO / "results" / "Journal_results" / "tables"
KDD_ORDER = ["normal", "dos", "probe", "r2l", "u2r"]
PRETTY = {"normal": "Normal", "dos": "DoS", "probe": "Probe", "r2l": "R2L", "u2r": "U2R"}


def grouped(mapping):
    g = defaultdict(list)
    for raw, cls in mapping.items():
        g[cls].append(raw)
    return {c: sorted(g[c]) for c in KDD_ORDER if c in g}


def counts(ds, **kw):
    b = get_dataset(ds, **kw)
    tr = b.train_loader.dataset.tensors[1].numpy()
    va = b.val_loader.dataset.tensors[1].numpy()
    te = b.test_loader.dataset.tensors[1].numpy()
    tot = np.bincount(np.concatenate([tr, va, te]), minlength=b.num_classes)
    return {n: int(c) for n, c in zip(b.class_names, tot)}


def esc(s):
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def main():
    c17 = counts("cicids2017", seed=42)
    c18 = counts("cse-cic-ids2018", seed=42, subsample_fraction=0.5)

    L = [
        r"% Generated by scripts/make_label_map_table.py from the loaders'",
        r"% LABEL_TO_CLASS dicts; do not edit by hand. Requires: \usepackage{booktabs}",
        r"\begin{table}[!ht]",
        r"\centering", r"\renewcommand{\arraystretch}{1.1}",
        r"\caption{Study-specific mapping of the native CIC-IDS2017 and "
        r"CSE-CIC-IDS2018 labels to the KDD five-class taxonomy, exactly as "
        r"implemented in the data loaders, with post-mapping flow counts over "
        r"the processed train+validation+test partitions (CSE-CIC-IDS2018 at "
        r"its configured 50\% sample, seed 42; counts vary marginally across "
        r"seeds). DoS aggregates volumetric denial-of-service and botnet "
        r"traffic; Probe covers reconnaissance/port scanning; R2L covers "
        r"remote-access credential attacks; U2R covers exploitation and code "
        r"execution (web attacks, SQL injection, infiltration). "
        r"CSE-CIC-IDS2018 contains no port-scan attack, so its Probe class is "
        r"empty by construction.}",
        r"\label{tab:label_mapping}",
        r"{\footnotesize",
        r"\begin{tabular}{l p{0.52\columnwidth} r}",
        r"\toprule",
        r"\textbf{KDD class} & \textbf{Native labels mapped to it} & \textbf{Flows} \\",
    ]
    for name, mapping, cnts in [("CIC-IDS2017", MAP17, c17),
                                ("CSE-CIC-IDS2018", MAP18, c18)]:
        L += [r"\midrule", rf"\multicolumn{{3}}{{l}}{{\textit{{{name}}}}} \\", r"\midrule"]
        g = grouped(mapping)
        for cls in KDD_ORDER:
            raws = g.get(cls, [])
            lbl = ", ".join(esc(r) for r in raws) if raws else r"\emph{(none)}"
            n = cnts.get(cls, 0)
            L.append(rf"{PRETTY[cls]} & {lbl} & {n:,} \\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    out = TAB / "table_label_mapping.tex"
    out.write_text("\n".join(L))
    print(f"[wrote] {out}")
    for name, c in [("cicids2017", c17), ("cse-cic-ids2018", c18)]:
        print(f"  {name}: {c}")


if __name__ == "__main__":
    main()
